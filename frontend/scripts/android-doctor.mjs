import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const windows = process.platform === 'win32';
let failures = 0;
const check = (ok, message) => { console.log(`${ok ? 'OK' : 'MISSING / INCOMPATIBLE'}: ${message}`); if (!ok) failures++; };
const run = (command, args) => { const r = spawnSync(command, args, { encoding: 'utf8', windowsHide: true }); return `${r.stdout || ''}${r.stderr || ''}`; };
console.log('MoneyFy Android prerequisites (no files or system settings are changed)');
check(Number(process.versions.node.split('.')[0]) >= 22, `Node ${process.versions.node}; requires Node 22+`);
const javaCommand = process.env.JAVA_HOME ? join(process.env.JAVA_HOME, 'bin', windows ? 'java.exe' : 'java') : 'java';
const javaText = run(javaCommand, ['-version']);
const javaMajor = Number(javaText.match(/version "(\d+)/)?.[1] || javaText.match(/openjdk (\d+)/)?.[1]);
check(javaMajor >= 21 && javaMajor <= 24, `Selected Java ${javaMajor || 'not found'}. Use JDK 21 (Capacitor compiles Java 21; this Gradle wrapper supports runtime Java up to 24). JAVA_HOME=${process.env.JAVA_HOME || '(unset)'}`);
const javac = process.env.JAVA_HOME ? join(process.env.JAVA_HOME, 'bin', windows ? 'javac.exe' : 'javac') : 'javac';
const compiler = Number(run(javac, ['-version']).match(/javac (\d+)/)?.[1]);
check(compiler >= 21 && compiler <= 24 && compiler === javaMajor, `Java compiler ${compiler || 'not found'} must match the selected JDK`);
const propertiesFile = join(root, 'android', 'local.properties');
const properties = existsSync(propertiesFile) ? readFileSync(propertiesFile, 'utf8') : '';
const fromProperties = properties.match(/^sdk\.dir\s*=\s*(.+)$/m)?.[1]?.trim().replace(/\\:/g, ':').replace(/\\\\/g, '\\');
const defaultSdk = windows ? join(process.env.LOCALAPPDATA || '', 'Android', 'Sdk') : join(process.env.HOME || '', process.platform === 'darwin' ? 'Library/Android/sdk' : 'Android/Sdk');
const sdk = fromProperties || process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT || defaultSdk;
check(existsSync(sdk), `Android SDK: ${sdk}`);
check(existsSync(join(sdk, 'platforms', 'android-36', 'android.jar')), 'Android SDK Platform 36');
const buildTools = join(sdk, 'build-tools');
const installed = existsSync(buildTools) ? readdirSync(buildTools) : [];
check(installed.some(v => Number(v.split('.')[0]) >= 35), `Android Build Tools 35+ (AGP default 35.0.0); installed: ${installed.join(', ') || 'none'}`);
const adb = join(sdk, 'platform-tools', windows ? 'adb.exe' : 'adb');
check(existsSync(adb), 'Android platform-tools (adb)');
check(existsSync(join(root, 'android', 'gradle', 'wrapper', 'gradle-wrapper.jar')), 'Bundled Gradle wrapper');
const studio = windows ? join(process.env.ProgramFiles || 'C:\\Program Files', 'Android', 'Android Studio', 'bin', 'studio64.exe') : '/Applications/Android Studio.app';
console.log(`INFO: Android Studio ${existsSync(studio) ? 'found' : 'not found at its default location (optional for command-line builds)'}`);
console.log(failures ? `\nAndroid build blocked by ${failures} prerequisite checks. No APK has been generated. See ../docs/ANDROID.md.` : '\nPrerequisites found. Run npm run android:apk. SDK licenses and dependency downloads may still be required.');
process.exitCode = failures ? 1 : 0;
