import { test, expect } from '@playwright/test';

test('Real signup, persistence, manual categories and Python calculations are integrated', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const email = `moneyfy-e2e-${Date.now()}@example.com`;
  await page.goto('/');
  await page.getByRole('button', { name: 'Sign in / Create account' }).click();
  await page.getByRole('button', { name: 'New here? Create an account' }).click();
  await page.getByRole('textbox', { name: 'Your name' }).fill('Integration Tester');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('Moneyfy-test-password-2026');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByText('Integration Tester · Personal account')).toBeVisible();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Privacy Center', exact: true }).click();
  await page.getByRole('checkbox', { name: /Allow demo transaction imports/ }).check();
  await page.getByRole('spinbutton', { name: 'Opening balance (₹)' }).fill('20000');
  await page.getByRole('spinbutton', { name: 'Emergency reserve (₹)' }).fill('5000');
  await page.getByRole('spinbutton', { name: 'Monthly salary (₹)' }).fill('30000');
  await page.getByRole('button', { name: 'Save financial inputs', exact: true }).click();
  await expect(page.getByText('Saved to database', { exact: true })).toBeVisible();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Transactions', exact: true }).click();
  await page.getByRole('checkbox', {name:'All months',exact:true}).check();
  await page.locator('input[type=file]').setInputFiles({ name: 'account.csv', mimeType: 'text/csv', buffer: Buffer.from('date,merchant,amount,direction\n2026-10-08,Corner Shop,600,debit\n2026-09-15,Corner Shop,300,debit') });
  await expect(page.locator('table tbody tr')).toHaveCount(2);
  await expect(page.getByRole('combobox', { name: 'Category for Corner Shop on 2026-10-08' })).toHaveValue('Uncategorized');
  await page.getByRole('combobox', { name: 'Category for Corner Shop on 2026-10-08' }).selectOption('Food');
  await expect(page.getByRole('combobox', { name: 'Category for Corner Shop on 2026-10-08' })).toHaveValue('Food');
  await page.reload();
  await expect(page.getByRole('combobox', { name: 'Category for Corner Shop on 2026-10-08' })).toHaveValue('Food');
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Money Autopilot', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Make room in everyday spending' })).toBeVisible();
  await page.getByRole('button', { name: 'Add to plan', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(page.getByText('Saved to database', { exact: true })).toBeVisible();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'What-If Simulator', exact: true }).click();
  const before = await page.getByText('Scenario closing balance').locator('..').locator('..').textContent();
  await page.getByRole('slider', { name: /Emergency expense/ }).fill('1000');
  await expect.poll(() => page.getByText('Scenario closing balance').locator('..').locator('..').textContent()).not.toBe(before);
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('Moneyfy-test-password-2026');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByText('Integration Tester · Personal account')).toBeVisible();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Privacy Center', exact: true }).click();
  await page.getByRole('button', { name: 'Delete data', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(page.getByRole('spinbutton', { name: 'Opening balance (₹)' })).toHaveValue('0');
  await page.reload();
  await expect(page.getByRole('spinbutton', { name: 'Opening balance (₹)' })).toHaveValue('0');
  expect(errors).toEqual([]);
});
