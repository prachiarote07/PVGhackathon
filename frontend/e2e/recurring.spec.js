import { test, expect } from '@playwright/test';

test('Public homepage keeps financial data behind login on desktop and mobile', async ({page}) => {
  await page.goto('/#Dashboard');
  await expect(page.getByRole('heading',{name:/A little clarity/})).toBeVisible();
  await expect(page.getByLabel('Rotating MoneyFy coin')).toBeVisible();
  for (const text of ['Available balance','Safe to spend','Financial health']) await expect(page.getByText(text,{exact:true})).toHaveCount(0);
  await page.screenshot({path:'test-results/redesign-public-desktop.png',fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:360,height:800});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBe(true);
  await page.getByRole('link',{name:'See how it works',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Simple steps. A clearer picture.'})).toBeVisible();
  await page.screenshot({path:'test-results/redesign-public-mobile.png',fullPage:true,animations:'disabled'});
});

test('Recurring payments progress across months, persist and reconcile imports once', async ({page}) => {
  test.setTimeout(120000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button',{name:'Sign in / Create account',exact:true}).click();
  await page.getByRole('button',{name:'New here? Create an account'}).click();
  await page.getByLabel('Your name',{exact:true}).fill('Recurring Tester');
  await page.getByLabel('Email',{exact:true}).fill(`recurring-${Date.now()}@example.com`);
  await page.getByLabel('Password',{exact:true}).fill('Moneyfy-recurring-test-2026');
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  const nav=page.getByRole('navigation',{name:'Main navigation'});
  await nav.getByRole('link',{name:'Privacy Center',exact:true}).click();
  await page.getByRole('checkbox',{name:/Allow demo transaction imports/}).check();
  await page.getByLabel('Balance date',{exact:true}).fill('2026-10-09');
  await page.getByLabel('Next salary date',{exact:true}).fill('2026-11-01');
  await page.getByRole('button',{name:'Save forecast dates'}).click();
  await expect(page.getByText('Saved to database',{exact:true})).toBeVisible();
  await nav.getByRole('link',{name:'Transactions',exact:true}).click();
  await page.getByLabel('Month and year').fill('2026-10');
  await page.getByRole('button',{name:'Add transaction',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Transaction name',{exact:true}).fill('House Rent');
  await dialog.getByLabel('Amount (₹)',{exact:true}).fill('8000');
  await dialog.getByLabel('Payment date',{exact:true}).fill('2026-10-05');
  await dialog.getByLabel('Does this transaction repeat regularly?').selectOption('monthly');
  await dialog.getByLabel('Starting date',{exact:true}).fill('2026-10-05');
  await dialog.getByLabel('First expected payment',{exact:true}).fill('2026-10-05');
  await dialog.getByRole('button',{name:'Save and track'}).click();
  await expect(dialog).toHaveCount(0);
  const payment=page.getByTestId('scheduled-payment');
  await expect(payment).toContainText('Paid');
  await expect(page.locator('table tbody tr')).toHaveCount(1);
  await page.getByRole('button',{name:'Next Month',exact:true}).click();
  await expect(payment).toContainText('2026-11-05');
  await expect(payment).toContainText('Expected');
  await expect(page.locator('table tbody tr')).toHaveCount(0);
  await page.getByRole('button',{name:'Postpone',exact:true}).click();
  await dialog.getByLabel('New payment date',{exact:true}).fill('2026-11-08');
  await dialog.getByRole('button',{name:'Confirm payment update'}).click();
  await expect(payment).toContainText('2026-11-08');
  await page.reload();
  await page.getByLabel('Month and year').fill('2026-11');
  await expect(payment).toContainText('Postponed');
  await page.getByRole('button',{name:'Skip',exact:true}).click();
  await page.getByRole('button',{name:'Confirm payment update'}).click();
  await expect(payment).toContainText('Skipped');
  for(const due of ['2026-12-05','2027-01-05']) {
    await page.getByRole('button',{name:'Next Month',exact:true}).click();
    await expect(payment).toContainText(due);
  }
  await page.getByLabel('Month and year').fill('2026-10');
  await page.locator('input[type=file]').setInputFiles({name:'rent.csv',mimeType:'text/csv',buffer:Buffer.from('date,merchant,amount,direction\n2026-10-06,House Rent,8000,debit')});
  await expect(page.locator('table tbody tr')).toHaveCount(1);
  await expect(page.locator('table tbody tr')).toContainText('CSV statement');
  await expect(payment).toContainText('Paid');
  await page.screenshot({path:'test-results/redesign-recurring-desktop.png',fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBe(true);
  await page.getByRole('button',{name:'Add recurring schedule',exact:true}).click();
  await expect(dialog).toBeVisible();
  await page.screenshot({path:'test-results/redesign-recurring-mobile.png',fullPage:true,animations:'disabled'});
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  expect(errors).toEqual([]);
});
