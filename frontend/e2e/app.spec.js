import { test, expect } from '@playwright/test';

test('All pages render; forecasts, approvals, imports, goals and deletion work', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Explore offline demo', exact: true }).click();
  await expect(page.getByRole('heading', { name: /A little clarity/ })).toBeVisible();
  await page.screenshot({ path: 'test-results/home-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Explore your demo' }).click();
  await expect(page.getByRole('heading', { name: /Good morning/ })).toBeVisible();
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true });
  for (const name of ['Transactions', 'Money Autopilot', 'What-If Simulator', 'Savings Goals', 'Financial Insights', 'How It Works', 'Privacy Center']) {
    await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name, exact: true }).click();
    await expect(page.locator('main h1')).toBeVisible();
  }
  await page.getByRole('checkbox', { name: /Allow demo transaction imports/ }).check();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Transactions', exact: true }).click();
  await page.getByText('Import statements or connect a fictional bank', { exact: true }).click();
  await page.getByRole('button', { name: 'Connect demo bank', exact: true }).first().click();
  await expect(page.getByRole('status')).toContainText('1 transactions added');
  await expect(page.getByRole('heading', { name: 'Standardized transaction' })).toBeVisible();
  await page.getByRole('button', { name: 'Sync demo transactions' }).click();
  await expect(page.getByRole('status')).toContainText('1 exact duplicates skipped');
  await page.locator('input[type=file]').setInputFiles({ name: 'sample.csv', mimeType: 'text/csv', buffer: Buffer.from('date,merchant,amount,direction\n2026-10-08,"Cafe, Pune",125.50,debit') });
  await page.getByRole('textbox', { name: 'Search transactions' }).fill('Cafe');
  await expect(page.locator('table tbody tr')).toHaveCount(1);
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Money Autopilot', exact: true }).click();
  await page.getByRole('button', { name: 'Add to plan' }).first().click();
  await expect(page.getByRole('dialog')).toContainText('No money moves');
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(page.getByText(/Planned ·/)).toBeVisible();
  await page.getByRole('button', { name: 'Modify', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Monthly reduction' }).fill('300');
  await page.getByRole('button', { name: 'Review change' }).click();
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(page.getByText('Planned · ₹300')).toBeVisible();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'What-If Simulator', exact: true }).click();
  const before = await page.getByText('Scenario closing balance').locator('..').locator('..').textContent();
  await page.getByRole('slider', { name: /Emergency expense/ }).fill('10000');
  const after = await page.getByText('Scenario closing balance').locator('..').locator('..').textContent();
  expect(after).not.toEqual(before);
  await page.getByRole('button', { name: 'Reset scenario' }).click();
  await expect(page.getByRole('slider', { name: /Emergency expense/ })).toHaveValue('0');
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Savings Goals', exact: true }).click();
  await page.getByRole('button', { name: 'Add a goal' }).click();
  await page.getByRole('textbox', { name: 'Goal name' }).fill('Laptop');
  await page.getByRole('spinbutton', { name: 'Target (₹)' }).fill('36000');
  await page.getByRole('button', { name: 'Save goal', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Laptop' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Laptop' })).toBeVisible();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Financial Insights', exact: true }).click();
  await page.getByRole('button', { name: 'Mark read', exact: true }).first().click();
  await expect(page.getByRole('button', { name: 'Mark unread', exact: true })).toBeVisible();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'How It Works', exact: true }).click();
  await page.getByRole('tab', { name: /You make the final call/ }).click();
  await expect(page.getByRole('tabpanel')).toContainText('Accept, reject or modify');
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Privacy Center', exact: true }).click();
  await page.getByRole('button', { name: 'Delete data', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  await page.reload();
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('moneyfy.demo.v1')));
  expect(stored.transactions).toHaveLength(0); expect(stored.goals).toHaveLength(0); expect(stored.imports).toHaveLength(0);
  expect(errors).toEqual([]);
});

test('Mobile navigation, theme and reduced motion', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  await page.getByRole('button', { name: 'Explore offline demo', exact: true }).click();
  await expect(page.getByRole('heading', { name: /A little clarity/ })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.getByRole('button', { name: 'Explore your demo' }).click();
  await page.getByRole('button', { name: 'Toggle navigation' }).click();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Savings Goals' }).click();
  await expect(page.getByRole('heading', { name: /Good things start/ })).toBeVisible();
  await page.getByRole('button', { name: 'Toggle light and dark theme' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/mobile-light.png', fullPage: true });
});
